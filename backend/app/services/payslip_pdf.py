import io

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

from app.models.employee import Employee
from app.models.payroll import PayrollRun, Payslip


def render_payslip_pdf(run: PayrollRun, slip: Payslip, employee: Employee, company_name: str) -> bytes:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    width, height = A4
    y = height - 25 * mm

    c.setFont("Helvetica-Bold", 16)
    c.drawString(20 * mm, y, company_name)
    y -= 8 * mm
    c.setFont("Helvetica-Bold", 12)
    c.drawString(20 * mm, y, f"Payslip — {run.month:02d}/{run.year}")
    y -= 10 * mm

    c.setFont("Helvetica", 10)
    rows = [
        ("Employee", f"{employee.full_name} ({employee.code})"),
        ("Email", employee.email),
        ("Working days", str(slip.working_days)),
        ("Present days", f"{slip.present_days:.1f}"),
        ("Absent days", f"{slip.absent_days:.1f}"),
        ("Unpaid leave days", f"{slip.unpaid_days:.1f}"),
        ("Half days", f"{slip.half_days:.1f}"),
        ("Late penalty (days)", f"{(slip.late_penalty_days or 0):.1f}"),
        ("", ""),
        ("Basic", f"{slip.basic:,.2f}"),
        ("HRA (40%)", f"{slip.hra:,.2f}"),
        ("Medical (10%)", f"{slip.medical:,.2f}"),
        ("Gross", f"{slip.gross:,.2f}"),
        ("Deductions", f"-{slip.deductions:,.2f}"),
        ("Tax", f"-{slip.tax:,.2f}"),
        ("", ""),
        ("Net Pay", f"{slip.net_pay:,.2f}"),
    ]
    for label, value in rows:
        if label == "" and value == "":
            y -= 3 * mm
            continue
        c.drawString(20 * mm, y, label)
        c.drawRightString(width - 20 * mm, y, value)
        y -= 6 * mm

    c.setFont("Helvetica-Oblique", 8)
    c.drawString(20 * mm, 15 * mm, "Generated by HCM Lite")
    c.showPage()
    c.save()
    return buf.getvalue()
